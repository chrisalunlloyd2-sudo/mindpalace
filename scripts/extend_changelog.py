#!/usr/bin/env python3
"""extend_changelog.py — deterministic CHANGELOG.md extension (issue #247).

Honors the #51 contract (CHANGELOG.md is generated, never hand-edited): this
script derives the 1.1.0-beta1 section straight from `git log`, the same
deterministic, commit-derived format the v1.0.0 lineage section uses
(one bullet per notable commit, description + short hash at line end).

Additive only: appends a dated section at EOF (or exits 0 as a no-op if the
marker already exists — idempotent). Never touches existing content.

Usage: python scripts/extend_changelog.py [--repo PATH]
"""
import argparse
import re
import subprocess
import sys

MARKER = "<!-- extend_changelog:v1.1.0-beta1 -->"
SINCE = "2026-09-17"
LINEAGE_TITLE = "1.1.0-beta1 ({since} .. {{head_date}}) — deterministic git-log extension (issue #247)".format(
    since=SINCE
)

# A bullet needs one of these prefixes; pure bookkeeping (docs sync, task
# lists, bot plumbing) is excluded — same "notable commits" bar as the
# v1.0.0 section's 199-commit -> 199-bullet selection.
NOTABLE = re.compile(
    r"^(feat|fix|perf)(\(|:| )|^(MP-\d+|#\d+|E2E)\b|^fix\(|^feat\("
)
EXCLUDE = re.compile(
    r"NEXT_100|AGENTS\.md|ARCHITECTURE|CHANGELOG|PERFORMANCE\.md|"
    r"doc[s]? (sync|reconcile|batch)|README: fix 404s"
)


def git(repo: str, args: list) -> str:
    """Git.

    Args: repo, args.
    """
    out = subprocess.run(
        ["git", "-C", repo] + args, capture_output=True, text=True, check=True
    )
    return out.stdout


def main() -> int:
    """Main (function)."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    args = ap.parse_args()

    lines = (git(args.repo, ["log", "--since=%s 00:00" % SINCE, "--no-merges",
                             "--pretty=%h|%ad|%s", "--date=short"])
             .splitlines())
    if not lines:
        print("no commits since %s — nothing to do" % SINCE)
        return 0

    hash_map = {}
    for ln in lines:
        h, date, subj = ln.split("|", 2)
        hash_map[h] = subj

    added, fixed, changed = [], [], []
    for ln in lines:
        h, date, subj = ln.split("|", 2)
        if EXCLUDE.search(subj) or not NOTABLE.search(subj):
            continue
        if subj.startswith("feat"):
            added.append("- %s (%s)" % (subj, h))
        elif subj.startswith("fix") or subj.startswith("perf"):
            fixed.append("- %s (%s)" % (subj, h))
        else:
            changed.append("- %s (%s)" % (subj, h))

    head = git(args.repo, ["rev-parse", "HEAD"]).strip()[:7]
    head_date = git(args.repo, ["log", "-1", "--pretty=%ad", "--date=short",
                                head]).strip()

    out = [MARKER.rstrip("\n"), "",
           "## " + LINEAGE_TITLE.format(head_date=head_date), ""]
    out.append("Deterministically generated by scripts/extend_changelog.py "
               "from `git log --since=%s --no-merges` at HEAD %s "
               "(%d notable entries; %d commits total in window). "
               "v1.0.0 lineage content above is untouched."
               % (SINCE, head, len(added) + len(fixed) + len(changed),
                  len(lines)))
    for title, rows in (("Added", added), ("Fixed", fixed), ("Changed", changed)):
        if rows:
            out += ["", "### %s (1.1.0-beta1 lineage)" % title, ""]
            out += rows
    out.append("")

    path = args.repo.rstrip("/\\") + "/CHANGELOG.md"
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        cur = f.read()
    if MARKER in cur:
        print("marker already present — idempotent no-op")
        return 0
    if not cur.endswith("\n"):
        cur += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cur + "\n".join(out))
    print("appended %d+%d+%d entries for %s..%s"
          % (len(added), len(fixed), len(changed), SINCE, head_date))
    return 0


if __name__ == "__main__":
    sys.exit(main())