#!/usr/bin/env python3
"""extend_changelog.py — deterministic CHANGELOG.md extension (issue #247).

Honors the #51 contract (CHANGELOG.md is generated, never hand-edited): this
script derives the 1.1.0-beta1 section straight from `git log`, the same
deterministic, commit-derived format the v1.0.0 lineage section uses
(one bullet per notable commit, description + short hash at line end).

Additive only: appends a dated section at EOF (or exits 0 as a no-op if the
marker already exists — idempotent). Never touches existing content.

Usage: python scripts/extend_changelog.py [--repo PATH]
"""
import argparse
import re
import subprocess
import sys

MARKER1 = "<!-- extend_changelog:v1.1.0-beta1 -->"
SINCE1 = "2026-09-17"
TITLE1 = "1.1.0-beta1 ({since} .. {{head_date}}) — deterministic git-log extension (issue #247)".format(
    since=SINCE1
)
MARKER2 = "<!-- extend_changelog:v1.1.0-beta1-ext2 -->"
SINCE2 = "2026-10-23"   # last documented commit date (marker1 freeze point, issue #412)
TITLE2 = "1.1.0-beta1 ext2 ({since} .. {{head_date}}) — deterministic git-log extension (issue #412)".format(
    since=SINCE2
)

# Extension windows in generation order; every window absent from the file is
# generated (additive, at EOF) — existing content is never rewritten, so
# running the sweep is idempotent per-window and repeat-safe.
WINDOWS = [
    {"marker": MARKER1, "since": SINCE1, "title": TITLE1},
    {"marker": MARKER2, "since": SINCE2, "title": TITLE2},
]

# A bullet needs one of these prefixes; pure bookkeeping (docs sync, task
# lists, bot plumbing) is excluded — same "notable commits" bar as the
# v1.0.0 section's 199-commit -> 199-bullet selection.
NOTABLE = re.compile(
    r"^(feat|fix|perf)(\(|:| )|^(MP-\d+|#\d+|E2E)\b|^fix\(|^feat\("
)
EXCLUDE = re.compile(
    r"NEXT_100|AGENTS\.md|ARCHITECTURE|CHANGELOG|PERFORMANCE\.md|"
    r"doc[s]? (sync|reconcile|batch)|README: fix 404s"
)


def git(repo: str, args: list) -> str:
    """Git.

    Args: repo, args.
    """
    out = subprocess.run(
        ["git", "-C", repo] + args, capture_output=True, text=True, check=True
    )
    return out.stdout


def generate_window(repo: str, since: str, title: str, marker: str, head_date: str) -> str:
    """Build one extension section from the git log in [since .. head]."""
    lines = (git(repo, ["log", "--since=%s 00:00" % since, "--no-merges",
                        "--pretty=%h|%ad|%s", "--date=short"])
             .splitlines())
    if not lines:
        return ""

    added, fixed, changed = [], [], []
    for ln in lines:
        h, date, subj = ln.split("|", 2)
        if EXCLUDE.search(subj) or not NOTABLE.search(subj):
            continue
        if subj.startswith("feat"):
            added.append("- %s (%s)" % (subj, h))
        elif subj.startswith("fix") or subj.startswith("perf"):
            fixed.append("- %s (%s)" % (subj, h))
        else:
            changed.append("- %s (%s)" % (subj, h))

    if not (added or fixed or changed):
        return ""

    head = git(repo, ["rev-parse", "HEAD"]).strip()[:7]
    out = [marker, "",
           "## " + title.format(head_date=head_date), ""]
    out.append("Deterministically generated by scripts/extend_changelog.py "
               "from `git log --since=%s --no-merges` at HEAD %s "
               "(%d notable entries; %d commits total in window). "
               "Earlier lineage content above is untouched."
               % (since, head, len(added) + len(fixed) + len(changed),
                  len(lines)))
    for kind, rows in (("Added", added), ("Fixed", fixed), ("Changed", changed)):
        if rows:
            out += ["", "### %s (1.1.0-beta1 lineage)" % kind, ""]
            out += rows
    out.append("")
    return "\n".join(out)


def main() -> int:
    """Main (function)."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    args = ap.parse_args()

    path = args.repo.rstrip("/\\") + "/CHANGELOG.md"
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        cur = f.read()
    if not cur.endswith("\n"):
        cur += "\n"

    head_date = git(args.repo, ["log", "-1", "--pretty=%ad", "--date=short"]).strip()
    appended_any = False
    for w in WINDOWS:
        if w["marker"] in cur:
            continue  # window already documented — idempotent per-window
        section = generate_window(args.repo, w["since"], w["title"], w["marker"], head_date)
        if not section:
            continue
        cur += "\n" + section
        appended_any = True
        print("appended window since=%s (marker %s)" % (w["since"], w["marker"]))

    if not appended_any:
        print("all windows already present — idempotent no-op")
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cur)
    return 0


if __name__ == "__main__":
    sys.exit(main())